  `last_join_event_at` bigint DEFAULT NULL COMMENT '最近进群排序时间(epoch毫秒)',
  `last_join_source_event_id` varchar(255) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL COMMENT '最近进群同时间决胜事件ID',
