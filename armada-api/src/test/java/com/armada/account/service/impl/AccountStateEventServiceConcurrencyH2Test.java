    @Test
    void androidFailureContextCommitsWithStateAndSurvivesMissingDiagnosisAndReallocationFailure() {
        AccountStateChangedEvent failure = proxyFailure("oa_failed", 2_000L, null);
        assertThat(service.applyStateChanged(failure)).isTrue();
        assertThat(service.applyStateChanged(failure)).isTrue();
        JdbcTemplate jdbc = new JdbcTemplate(dataSource);
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM account_online_attempt_log", Integer.class)).isOne();
        TenantContext.set(1L);
        try {
            assertThat(attemptLogService.proxyFailureAt(ACCOUNT_ID, 1_999L)).isNull();
            assertThat(attemptLogService.proxyFailureAt(ACCOUNT_ID, 2_000L).onlineAttemptId()).isEqualTo("oa_failed");
            AccountOnlineCommandService online = Mockito.mock(AccountOnlineCommandService.class);
            ProtocolCommandOutboxService outbox = Mockito.mock(ProtocolCommandOutboxService.class);
            when(outbox.findOnlineAttemptProxyId(ACCOUNT_ID, "oa_failed")).thenReturn(Optional.of(7L));
            when(ipProxyService.markFailedProxyUnavailable(ACCOUNT_ID, 7L, 2_000L)).thenReturn(true);
            when(online.reonlineAfterProxyFailure(ACCOUNT_ID, "oa_failed", 7L, 2_000L))
                    .thenThrow(new IllegalStateException("no idle proxy")).thenReturn(null);
            ProxyFailedRecoveryDispatcher dispatcher = new ProxyFailedRecoveryDispatcher(
                    stateMapper, attemptLogService, new ProxyFailedRecoveryCoordinator(ipProxyService, online, outbox));
            assertThat(dispatcher.dispatchOnce()).isOne();
            // 重建 dispatcher 模拟进程内存丢失，仍能从已提交状态和失败上下文继续同一尝试。
            assertThat(new ProxyFailedRecoveryDispatcher(stateMapper, attemptLogService,
                    new ProxyFailedRecoveryCoordinator(ipProxyService, online, outbox)).dispatchOnce()).isOne();
            verify(online, Mockito.times(2)).reonlineAfterProxyFailure(ACCOUNT_ID, "oa_failed", 7L, 2_000L);
            TenantContext.set(2L);
            assertThat(attemptLogService.proxyFailureAt(ACCOUNT_ID, 2_000L)).isNull();
        } finally {
            TenantContext.clear();
        }
    }

    @Test
    void failedContextInsertRollsBackStateAndStaleFailureDoesNotWriteContext() {
        JdbcTemplate jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("ALTER TABLE account_online_attempt_log ADD CHECK (diagnosis_code <> 'PROXY_FAILED')");
        assertThatThrownBy(() -> service.applyStateChanged(proxyFailure("oa_failed", 2_000L, 7L)))
                .isInstanceOf(RuntimeException.class);
        assertThat(jdbc.queryForObject("SELECT last_state_sync_time FROM account_state", Long.class))
                .isEqualTo(1_000L);
        assertThat(service.applyStateChanged(proxyFailure("oa_old", 999L, 6L))).isFalse();
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM account_online_attempt_log", Integer.class)).isZero();
    }

