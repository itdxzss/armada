  KEY `idx_wa_group_participant_exit` (`tenant_id`,`group_id`,`last_exited_at`),
  KEY `idx_wa_group_participant_phone` (`tenant_id`,`phone`,`group_id`),
  CONSTRAINT `ck_wa_group_participant_exit` CHECK (((`last_exit_type` is null) or (`last_exit_type` in (_ascii'LEFT',_ascii'REMOVED',_ascii'UNKNOWN')))),
  CONSTRAINT `ck_wa_group_participant_identity` CHECK (((`pn_jid` is not null) or (`lid_jid` is not null))),
  CONSTRAINT `ck_wa_group_participant_presence` CHECK ((`presence_status` in (0,1,2))),
  CONSTRAINT `ck_wa_group_participant_role` CHECK ((`role` in (0,1,2,3)))
) ENGINE=InnoDB AUTO_INCREMENT=883980 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='WhatsApp群成员当前身份、presence、role和最近进退事实';
