    private static AccountStateChangedEvent normalGroupOfflineEvent(long occurredAt) {
        return new AccountStateChangedEvent(
                1L, ACCOUNT_ID, PROTOCOL_ACCOUNT_ID,
                "ONLINE", "OFFLINE", occurredAt,
                "NORMAL_GROUP_ACCOUNT_NOT_ONLINE", null, "normal_group_creation", null, null);
    }

    private void assertOnlineAt(long occurredAt) {
        JdbcTemplate jdbc = new JdbcTemplate(dataSource);
        assertThat(jdbc.queryForObject(
                "SELECT login_state FROM account_state WHERE account_id = 100",
                Integer.class)).isEqualTo(AccountLoginStateCode.ONLINE);
        assertThat(jdbc.queryForObject(
                "SELECT last_state_sync_time FROM account_state WHERE account_id = 100",
                Long.class)).isEqualTo(occurredAt);
    }

    private void assertNoNormalGroupSideEffects() {
        verify(sideEffect, never()).afterStateChanged(
                org.mockito.ArgumentMatchers.any(Account.class),
                org.mockito.ArgumentMatchers.argThat(event ->
                        "normal_group_creation".equals(event.source())),
                org.mockito.ArgumentMatchers.anyLong());
    }

    private static void await(CountDownLatch latch) {
        try {
            if (!latch.await(2, TimeUnit.SECONDS)) {
                throw new IllegalStateException("等待并发测试信号超时");
            }
        } catch (InterruptedException ex) {
            Thread.currentThread().interrupt();
            throw new IllegalStateException("并发测试被中断", ex);
        }
    }

    private void execute(String sql) throws SQLException {
        try (Connection connection = dataSource.getConnection();
             Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }

